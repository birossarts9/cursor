import pandas as pd

# ------------------------------------------------------------
# 1. 가상 데이터 생성 (Mock Data)
# ------------------------------------------------------------
data = [
    # [13:00 수집] 84A와 59B 매물이 수집됨 (둘 다 5.1일자)
    ["자이", "101동", "84A", 9000, "26.05.01", "2026-05-08 13:00:00"],
    ["자이", "101동", "59B", 8000, "26.05.01", "2026-05-08 13:00:00"],
    
    # [14:00 수집] 소장님이 84A 매물만 5.8일자로 갱신함! (🔥 여기서 포착되어야 함)
    ["자이", "101동", "84A", 9000, "26.05.08", "2026-05-08 14:00:00"], 
    ["자이", "101동", "59B", 8000, "26.05.01", "2026-05-08 14:00:00"],
    
    # [23:00 수집] 소장님 퇴근. 아무 변화 없음. 크롤러만 수집함. (무시되어야 함)
    ["자이", "101동", "84A", 9000, "26.05.08", "2026-05-08 23:00:00"], 
    ["자이", "101동", "59B", 8000, "26.05.01", "2026-05-08 23:00:00"]  
]
df = pd.DataFrame(data, columns=["단지명", "동/호수", "층/타입", "가격", "확인일자", "수집일시"])


# ------------------------------------------------------------
# 2. 대표님의 엑셀 로직 적용 (단지+동+층 스펙 기반 그룹핑)
# ------------------------------------------------------------

# 1단계: 엑셀처럼 스펙 기준으로 완벽하게 정렬 (단지->동->층->수집일시)
df = df.sort_values(["단지명", "동/호수", "층/타입", "수집일시"])

# 2단계: 이전 행 데이터 가져오기 (엑셀의 이전 줄 참조)
df["이전_단지명"] = df["단지명"].shift(1)
df["이전_동"] = df["동/호수"].shift(1)
df["이전_층타입"] = df["층/타입"].shift(1)
df["이전_가격"] = df["가격"].shift(1)
df["이전_확인일자"] = df["확인일자"].shift(1)

# 3단계: 동일매물 및 가격변동 판별 (대표님의 엑셀 M열, O열 로직)
cond_spec = (df["단지명"] == df["이전_단지명"]) & (df["동/호수"] == df["이전_동"]) & (df["층/타입"] == df["이전_층타입"])
cond_price = (df["가격"] == df["이전_가격"])

df["매물상태"] = "새매물"
df.loc[cond_spec & ~cond_price, "매물상태"] = "가격변동의심"
df.loc[cond_spec & cond_price, "매물상태"] = "동일매물"

# 4단계: 갱신포착 (대표님의 엑셀 N열, P열 로직)
# "동일매물이면서 날짜만 바뀐 경우"
df["🚨갱신포착"] = (df["매물상태"] == "동일매물") & (df["확인일자"] != df["이전_확인일자"])


# ------------------------------------------------------------
# 3. 결과 출력
# ------------------------------------------------------------
print("\n=== 가상 데이터 전체 계산 결과 ===")
print(df[["수집일시", "층/타입", "확인일자", "매물상태", "🚨갱신포착"]])

print("\n=== 최종 갱신 타점 (이것만 대시보드 통계로 감) ===")
result = df[df["🚨갱신포착"] == True]
print(result[["수집일시", "층/타입", "이전_확인일자", "->", "확인일자", "🚨갱신포착"]])